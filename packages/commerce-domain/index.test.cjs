const {test} = require('node:test');
const assert = require('node:assert/strict');
const {groupSavings,groupState,validateCampaign,validateDemoAlias,totalKobo} = require('./index.cjs');
const future = '2099-01-01T00:00:00.000Z';
const past = '2020-01-01T00:00:00.000Z';
test('group discount computed in integer kobo',()=>assert.equal(groupSavings(12000000,10800000),1200000));
test('price inflation is refused',()=>assert.throws(()=>groupSavings(500,600),/EXCEEDS/));
test('negative money refused',()=>assert.throws(()=>groupSavings(-1,0),/INVALID_AMOUNT/));
test('unfilled team is open',()=>assert.equal(groupState({members:1,minMembers:2,maxMembers:5,expiresAt:future}),'open'));
test('minimum team qualifies',()=>assert.equal(groupState({members:2,minMembers:2,maxMembers:5,expiresAt:future}),'confirmed'));
test('full team marks capacity',()=>assert.equal(groupState({members:5,minMembers:2,maxMembers:5,expiresAt:future}),'full'));
test('expired incomplete group fails',()=>assert.equal(groupState({members:1,minMembers:2,maxMembers:5,expiresAt:past}),'expired'));
test('already qualified group remains confirmed after expiration',()=>assert.equal(groupState({members:2,minMembers:2,maxMembers:5,expiresAt:past}),'confirmed'));
test('cannot exceed capacity',()=>assert.throws(()=>groupState({members:6,minMembers:2,maxMembers:5,expiresAt:future}),/CAPACITY/));
test('valid campaign parameters',()=>assert.equal(validateCampaign({minMembers:2,maxMembers:8,durationHours:24}),true));
test('invalid short expiry',()=>assert.throws(()=>validateCampaign({minMembers:2,maxMembers:5,durationHours:0}),/DURATION/));
test('invalid threshold',()=>assert.throws(()=>validateCampaign({minMembers:1,maxMembers:5,durationHours:24}),/MIN_MEMBERS/));
test('demo alias rejects PII and control chars',()=>{assert.throws(()=>validateDemoAlias('my@email.com'),/ALIAS/);assert.throws(()=>validateDemoAlias('a\n'),/ALIAS/);});
test('demo alias accepted',()=>assert.equal(validateDemoAlias('shopper_001'),'shopper_001'));
test('quantity and money safe',()=>assert.equal(totalKobo(250000,3),750000));
test('fractional quantity rejected',()=>assert.throws(()=>totalKobo(250000,0.5),/QUANTITY/));
